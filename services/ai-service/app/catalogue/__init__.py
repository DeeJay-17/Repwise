"""The exercise catalogue, a slim copy of the app's bundled catalogue.

Generated by apps/mobile/scripts/build_catalogue.py. Exercise ids are shared with the app,
so a plan generated here can be shown and logged there.
"""

import json
from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import BaseModel

from app.models import Limitation, MuscleGroup

CATALOGUE_FILE = Path(__file__).parent / "exercises.json"


class Exercise(BaseModel):
    id: str
    name: str
    category: Literal["strength", "plyometric", "cardio"]
    level: str
    mechanic: str | None
    primaryMuscles: list[MuscleGroup]  # noqa: N815 - matches the JSON file
    secondaryMuscles: list[MuscleGroup]  # noqa: N815
    equipment: list[str]
    defaultTarget: Literal["reps", "time"]  # noqa: N815


@lru_cache
def all_exercises() -> tuple[Exercise, ...]:
    data = json.loads(CATALOGUE_FILE.read_text())
    return tuple(Exercise.model_validate(e) for e in data["exercises"])


def exercise_by_id() -> dict[str, Exercise]:
    return {e.id: e for e in all_exercises()}


# Exercises left out for each limitation. Matching is on id fragments and categories,
# deliberately cautious: when in doubt, the exercise is excluded.
_LIMITATION_RULES: dict[Limitation, tuple[set[str], set[str]]] = {
    # limitation: (excluded categories, excluded id fragments)
    "no_jumping": ({"plyometric"}, {"jump", "star_jump", "split_jump"}),
    "knees": (
        {"plyometric"},
        {"jump", "lunge", "split_squat", "step_up", "hack_squat", "leg_extension"},
    ),
    "lower_back": (
        set(),
        {"deadlift", "good_morning", "bent_over", "t_bar_row", "back_extension", "ab_rollout"},
    ),
    "shoulders": (
        set(),
        {"overhead", "shoulder_press", "arnold", "upright_row", "dip", "military", "pullover"},
    ),
    "wrists": (set(), {"push_up", "plank", "mountain_climber", "floor_press", "skullcrusher"}),
}


def is_allowed(exercise: Exercise, limitations: list[Limitation]) -> bool:
    for limitation in limitations:
        categories, fragments = _LIMITATION_RULES[limitation]
        if exercise.category in categories:
            return False
        if any(fragment in exercise.id for fragment in fragments):
            return False
    return True


def shortlist(equipment_ids: list[str], limitations: list[Limitation]) -> list[Exercise]:
    """Exercises the user can do with their equipment and that respect their limitations."""
    owned = set(equipment_ids)
    return [e for e in all_exercises() if set(e.equipment) <= owned and is_allowed(e, limitations)]
